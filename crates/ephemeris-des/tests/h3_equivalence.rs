//! H3 golden-equivalence gate: `h3o` (Rust) must reproduce the canonical
//! Python `h3` library's parent-lookup and centroid for a diverse set of
//! cells. This test gates the surface-materialization migration — the moment
//! Rust owns the node→cell rollup it relies on `h3o::CellIndex::parent` and
//! `h3o::LatLng::from(cell)` matching what the rest of the platform (Python
//! demand/heatmap serializers, h3 4.4.x) computes. If this diverges, the wire
//! frame's `cell_h3` / `cell_centroid_*` columns silently disagree with every
//! other H3 consumer.
//!
//! # Fixture
//!
//! 26 cells at H3 resolution 6 (the live node resolution, where
//! `cell_to_parent(res 3)` does real 3-level work):
//!   * 10 — actual node atlas (res-6 cells re-indexed from real node geography,
//!          `assets/world/knn_30/nodes.json`)
//!   * 10 — globe-sampled (distinct icosahedron faces)
//!   *  6 — pentagon-adjacent (neighbors of the 12 res-6 pentagon cells)
//!
//! Each tuple is `(cell_u64, expected_parent_res3_u64, centroid_lat, centroid_lng)`
//! where the expected values were baked from Python `h3` 4.4.2. The Python
//! library is NOT invoked at test time.
//!
//! # Regenerating the fixture
//!
//! Run the one-off generator (NOT committed to main) and paste its stdout
//! over the `FIXTURE` constant below:
//!
//! ```sh
//! services/node-engine/.venv/bin/python scripts/generate_h3_golden_fixture.py
//! ```

