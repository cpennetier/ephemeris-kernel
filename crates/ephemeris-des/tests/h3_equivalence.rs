#[test]
fn fixture_has_expected_shape() {
    // Guards against an accidental truncation when the fixture is regenerated.
    assert_eq!(FIXTURE.len(), 26, "fixture must carry all 26 golden cells");
}

#[test]
fn parent_res3_matches_python_h3() {
    let mut failures: Vec<String> = Vec::new();
    for &(cell_u64, expected_parent, _lat, _lng) in FIXTURE {
        let cell = match CellIndex::try_from(cell_u64) {
            Ok(c) => c,
            Err(e) => {
                failures.push(format!("cell {cell_u64:#x}: invalid CellIndex: {e}"));
                continue;
            }
        };
        let parent = cell
            .parent(Resolution::Three)
            .expect("res-6 cell always has a res-3 ancestor");
        let got = u64::from(parent);
        if got != expected_parent {
            failures.push(format!(
                "cell {cell_u64:#x}: h3o parent {got:#x} != python {expected_parent:#x}"
            ));
        }
    }
    assert!(
        failures.is_empty(),
        "h3o/python parent divergence on {} cell(s):\n{}",
        failures.len(),
        failures.join("\n")
    );
}

#[test]
fn centroid_matches_python_h3() {
    let mut failures: Vec<String> = Vec::new();
    for &(cell_u64, _expected_parent, expected_lat, expected_lng) in FIXTURE {
        let cell = CellIndex::try_from(cell_u64).expect("valid fixture cell");
        let ll = LatLng::from(cell);
        let dlat = (ll.lat() - expected_lat).abs();
        let dlng = (ll.lng() - expected_lng).abs();
        if dlat > CENTROID_TOL_DEG || dlng > CENTROID_TOL_DEG {
            failures.push(format!(
                "cell {cell_u64:#x}: h3o ({:.15}, {:.15}) vs python ({:.15}, {:.15}) — Δlat={dlat:.3e} Δlng={dlng:.3e}",
                ll.lat(),
                ll.lng(),
                expected_lat,
                expected_lng
            ));
        }
    }
    assert!(
        failures.is_empty(),
        "h3o/python centroid divergence (tol {CENTROID_TOL_DEG:e}°) on {} cell(s):\n{}",
        failures.len(),
        failures.join("\n")
    );
}
